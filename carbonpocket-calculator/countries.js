// A bandeira é derivada do código ISO; nunca é armazenada, para manter o dado normalizado e permitir o mapa.
window.flagDe = function flagDe(code) {
  if (!/^[A-Z]{2}$/.test(code)) return '🌍';
  return String.fromCodePoint(
    ...code.split('').map((character) => 0x1f1e6 + character.charCodeAt(0) - 65),
  );
};
