// Nomes de países: gerados pelo Intl em vez de manter tabela manual por idioma.
// Substitui a lista em inglês por nomes no idioma ativo, com fallback para o código.
const COUNTRY_CODES = [
  'BR', 'AR', 'CL', 'CO', 'MX', 'US', 'CA', 'GB', 'IE', 'PT', 'ES', 'FR', 'DE',
  'IT', 'NL', 'BE', 'CH', 'AT', 'SE', 'NO', 'DK', 'FI', 'PL', 'RU', 'TR', 'CN',
  'JP', 'KR', 'IN', 'AU', 'NZ', 'ZA', 'NG', 'EG', 'AE'
];
function countryName(code, lang) {
  try {
    return new Intl.DisplayNames([lang], { type: 'region' }).of(code) || code;
  } catch (e) {
    return code;
  }
}
function countryOptions(lang) {
  return COUNTRY_CODES.map(function (code) {
    return { code: code, label: countryName(code, lang) };
  });
}